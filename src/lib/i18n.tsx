const LanguageContext = createContext<LanguageCode>("en");

export function LanguageProvider({ language, children }: { language: LanguageCode; children: React.ReactNode }) {
  return <LanguageContext.Provider value={language}>{children}</LanguageContext.Provider>;
}

/** Returns { language, t } — t(key) looks up the current language's string, falling back to English. */
export function useLanguage() {
  const language = useContext(LanguageContext);
  const t = (key: TranslationKey): string => translations[language]?.[key] ?? translations.en[key];
  return { language, t };
}
